"""Parameter names observed on any ZTE device, probed on every device.

Discovery mines each router's own web UI, which answers what *that* firmware's
pages happen to reference. Two devices do not mine the same set: the reference
MC7010 yields 658 names and the MC888 Pro in issue #56 answered 102 that appear
nowhere in the MC7010's set at all. Whether a name appears in a device's own
JavaScript and whether that device answers it are independent facts, and
probing only what a device mentions conflates them.

So every device is probed with this union as well as with its own mined names.
A name here costs one entry in a batch request and answers the question the
download exists to ask; a name missing here can only be found by whichever
device happens to mention it.

**Names only.** No values, no sample data, nothing device-specific beyond the
vocabulary the firmware itself publishes in its web pages.

Provenance, and the two kinds are not equivalent:

  - **Observed.** A device mined or answered the name.
      - MC7010, firmware `IRL_H3G_MC7010DV1.0.0B03`, mined and probed
        2026-09-02.
      - MC888 Pro, firmware `BD_ABPLMC888PROMODV1.0.0B01`, from the
        diagnostics downloads attached to issue #56 on 2026-09-01 and
        2026-09-02. The second was taken on 3.3.9 with three canaries held,
        so the names it left silent are absent rather than unproven, and it
        added 27 names to this set.
  - **Reported by another project.** `EXPECTED_NAMES` holds names taken from
    `Kajkac/ZTE-MC-Home-assistant-repo`'s `SENSOR_NAMES` map, read 2026-09-02.
    That map is what its integration asks for across the MC801, MC888, MC889
    and G5 Ultra, which is evidence that ZTE firmware somewhere uses those
    names. It is not evidence that any device answers them, and a name there
    that is silent on every device we ever see means the other project carried
    a name no hardware answers rather than that our probe failed.

Write commands are excluded: `run_discovery` never probes a name that appears
as a `goformId`, because reading one is at best meaningless and at worst a
write. Add to this list by observation — a name that some device actually
answered or that its web UI actually referenced — never by invention.
"""

